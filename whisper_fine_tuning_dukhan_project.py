def is_valid_audio(example):
    try:
        audio_dict = example["audio"]
        if audio_dict is None or "bytes" not in audio_dict or audio_dict["bytes"] is None:
            return False

        # Manually decode the audio bytes with try-except to handle unrecognized formats
        audio_bytes = audio_dict["bytes"]
        with io.BytesIO(audio_bytes) as f:
            array, sample_rate = sf.read(f)

        # Convert to mono if multi-channel
        if array.ndim > 1:
            array = array.mean(axis=-1)

    except Exception:
        # Successfully catch LibsndfileError and any other decoding anomalies
        return False

    if array is None or sample_rate is None or len(array) == 0:
        return False
    if not np.isfinite(array).all():
        return False

    duration = len(array) / sample_rate
    # Exclude clips that are too short, completely silent, or exceed Whisper's 30-second window
    if duration < MIN_AUDIO_SECONDS or duration > MAX_AUDIO_SECONDS:
        return False
    if np.max(np.abs(array)) < 1e-4:
        return False
    return True

